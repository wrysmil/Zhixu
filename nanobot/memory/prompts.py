"""Phase 2 记忆抽取的 LLM 提示词常量。

集中管理所有抽取提示词，便于单测断言稳定性。
每个 prompt 对应一个独立的 LLM 调用阶段。
"""

# =============================================================================
# §4.1 语义记忆抽取（双轨：user_profile + task_experience）
# =============================================================================
SEMANTIC_EXTRACTION_PROMPT = """
## 任务：语义记忆抽取

从对话历史中抽取两类语义记忆：**用户画像** 和 **任务经验**。

### 输出格式（严格 JSON）
{
  "memories": [
    {
      "content": "记忆内容（简洁、可检索）",
      "type": "FACT | PREFERENCE | RULE | SKILL | ERROR",
      "priority": "long_term | short_term",
      "importance": 0.5-1.0,
      "tags": ["tag1", "tag2"],
      "subject": "主语短语",
      "predicate": "谓语短语"
    }
  ],
  "experiences": [
    {
      "content": "经验内容（可复用的操作/教训）",
      "type": "EXPERIENCE | SKILL | ERROR",
      "priority": "long_term | short_term",
      "importance": 0.5-1.0,
      "tags": ["tag1", "tag2"],
      "subject": "主语短语",
      "predicate": "谓语短语"
    }
  ]
}

### 分类规则

**memories（用户画像）**：
- FACT：用户身份、背景、环境（工作领域、技术栈、项目名）
- PREFERENCE：工作习惯、偏好设置、拒绝或倾向的方式
- RULE：用户明确要求的约束（命名规范、目录结构、命令规范）
- SKILL：用户掌握的工具/语言/框架（推断自提问内容）
- ERROR：用户遇到过的常见错误模式

**experiences（任务经验）**：
- EXPERIENCE：可复用的成功操作流程、解决方案
- SKILL：完成任务的有效方法/技巧
- ERROR：踩过的坑、失败的原因

### 严格过滤（不记录）
- 一次性任务请求（除非揭示了用户偏好）
- 任务产物细节（文件名、代码片段、输出内容）
- 打招呼/寒暄/确认/感谢
- 系统状态、错误堆栈
- AI 回复内容（只记录用户意图）
- **用户对助手的操作指令**（"打开 Chrome 查看"、"帮我把日志排序"、"请执行 make build"）——
  那是让人去做的事，不是可复用的记忆

### 质量要求
- content 用第一人称"用户"或第三人称描述，不是"你"
- **content 必须以主语开头**（主语 = subject 字段里那个主语短语），用陈述句表述。
  检索期会把"以操作动词开头（打开/安装/部署/执行…）且没有合法主语"的 fact 判成
  操作指令并丢弃，所以主语开头是事实类记忆的硬要求：
  ✅ "项目 alpha-app 统一使用 Jenkins 部署"（subject=项目 alpha-app）
  ✅ "用户偏好用 rsync 同步数据"（subject=用户）
  ❌ "部署项目统一使用 Jenkins"（动词开头 → 检索期会被当成操作指令）
  ❌ "打开 Chrome 浏览器查看"（这是给助手的指令，不是事实）
- **subject**：这条记忆的**主语短语**（如「用户」「项目 alpha-app」「部署流程」）。尽量与
  情节记忆的 entities 用同一说法，便于两者互相关联；判断不出精确主语时给最贴近的，
  **不要留空**（content 开头用的就是它）
- **predicate**：主语与内容之间的关系短语（如「使用」「位于」「偏好」）
- FACT 必须是用户明确说过或可从上下文直接推断的，不是 AI 猜测
- 不做过度泛化（"用户总是..."）
- importance 默认 0.7；需要优先召回的设为 0.9+；低价值设为 0.5
- experiences 是可复用的操作流程/方法，**允许**以动作词开头（"先 X 再 Y"）；它们不是 fact，
  不受"主语开头"与动作词惩罚的影响

### 示例
输入：用户问"帮我把 /tmp/logs 下的日志按大小排序"，后续又说"我习惯用 rsync 同步数据"
输出：
{
  "memories": [
    {"content": "用户有使用命令行处理文件的习惯", "type": "PREFERENCE", "priority": "long_term", "importance": 0.6, "tags": ["cli"], "subject": "用户", "predicate": "有使用命令行处理文件的习惯"}
  ],
  "experiences": [
    {"content": "使用 ls -lS 可按大小排序文件", "type": "SKILL", "priority": "short_term", "importance": 0.7, "tags": ["cli", "文件操作"]}
  ]
}
"""

