# =============================================================================
# §4.1 语义记忆抽取（双轨：user_profile + task_experience）
# =============================================================================
SEMANTIC_EXTRACTION_PROMPT = """
## 任务：语义记忆抽取（保守模式）

你负责把本批对话中**未来仍有复用价值**的信息写入长期记忆。默认宁缺毋滥：
无法确认归属、证据或持久价值时，输出空数组。

### 四类输入，先分类再抽取

1. **用户画像**：用户明确陈述的身份、背景、长期偏好、稳定约束。
2. **项目知识**：用户明确确认的项目状态、架构决策、业务边界或已验证结论。
3. **任务经验**：本批用户确认或工具结果实际验证过的成功流程、失败教训、可复用方法。
4. **只进入情节/不进入长期记忆**：一次性事件、当前任务过程、计划、建议、问题、回忆请求。

问题前提、回忆请求、任务指令不是事实。特别地：

> “我们以前处理过类似问题，你能找回当时确认的方案，并说明这次需要先核对哪些证据吗？”

这是**回忆请求 + 问题前提**，不是“用户及其团队此前处理过……”的事实证据；
不得据此生成用户画像、偏好、规则或经验。

### 输出格式（严格 JSON）
{
  "memories": [
    {
      "content": "记忆内容（简洁、可检索、陈述句）",
      "type": "FACT | PREFERENCE | RULE | SKILL | ERROR",
      "priority": "long_term | short_term",
      "importance": 0.5-1.0,
      "tags": ["tag1", "tag2"],
      "subject": "主语短语",
      "predicate": "谓语短语",
      "evidence": "本批 user 消息中支持这条内容的逐字原文"
    }
  ],
  "experiences": [
    {
      "content": "经验内容（可复用的操作/教训）",
      "type": "EXPERIENCE | SKILL | ERROR",
      "priority": "long_term | short_term",
      "importance": 0.5-1.0,
      "tags": ["tag1", "tag2"],
      "subject": "主语短语",
      "predicate": "谓语短语",
      "evidence": "本批 user 或 tool 结果中支持该经验有效性的逐字原文"
    }
  ]
}

### 抽取边界（按顺序判断）

1. **是否持久有用？** 只对跨会话、跨任务仍有价值的内容抽取。一次性故障、
   当天日志、临时文件名、任务产物和寒暄不进入长期记忆。
2. **是否同义于问题/任务/计划？** 是则丢弃。不要从“你能找回……吗”
   反推出用户经历，不要从“帮我检查……”反推出用户偏好。
3. **是否有本批证据？** memories 的 evidence 必须是本批 [user] 消息逐字原文；
   experiences 的 evidence 必须来自本批 user 消息或 [tool] 结果。
   assistant 回复、检索结果、scratchpad、系统状态和 AI 自己的计划都不是证据。
4. **用户是在陈述还是在提问？** 提问、假设、请求、条件句、待验证方案只可进入
   情节，不可写成事实。用户说“如果……”“也许……”“我想让你……”同理。
5. **用户是否独立验证？** 未验证的用户陈述用“用户报告/用户表示”保留归属，
   不得写成客观事实；只有本批工具结果或用户明确确认才可写成已验证结论。
6. **是否应只进入 episode？** 当前事故经过、任务步骤和一次性排障过程交给
   episode。只有从中提炼出跨事件成立、且用户/工具结果支持的规律，才进入
   experiences。
7. **是否重复？** 同一主体、同一属性、同一含义只输出一次；优先复用已有表述，
   不要拆分出多条近义事实。无法确定是否更新时宁可少写，不要猜测覆盖。
8. **是否敏感？** 不保存密码、token、API key、私钥、完整身份证件、支付信息、
   原始敏感日志或与长期服务无关的个人标识。

### 类型规则

- FACT：用户身份、背景、环境、项目事实；未验证的写成“用户报告……”。
- PREFERENCE：用户明确表达的工作习惯、倾向、拒绝方式。
- RULE：用户明确要求长期遵守的约束。
- SKILL：用户明确说自己掌握/使用过的工具、语言、框架；不要只因为用户会提问就推断。
- ERROR：用户明确遇到过的可复用错误模式；当前一次报错本身通常只进 episode。
- EXPERIENCE：有可复用步骤且有结果证据；generic advice（泛泛建议）不算经验。

### 内容质量

- content 用“用户/项目/流程”等主语开头的陈述句，不要用“你”。
- **content 必须以主语开头**（主语 = subject 字段里那个主语短语）。检索期会把
  以操作动词开头、又没有合法主语的 fact 判成操作指令并丢弃。
- subject 填最贴近的主语短语；predicate 填“使用/位于/偏好/导致”等关系短语。
- importance 默认 0.7；跨会话关键事实用 0.9+；低价值用 0.5。
- experiences 允许以“先 X 再 Y”开头；它们不是 fact，不受操作词惩罚。
- 输出前自检：如果把这条记忆放到 30 天后，它是否仍然能帮助另一个会话？
  如果答案不明确，删除它。

### 示例

输入：
[user] 我住杭州，能推荐本地咖啡吗？
[assistant] 当然。
输出：
{
  "memories": [
    {"content": "用户住在杭州", "type": "FACT", "priority": "long_term", "importance": 0.8, "tags": ["居住地"], "subject": "用户", "predicate": "居住地", "evidence": "我住杭州"}
  ],
  "experiences": []
}

输入：
[user] 我们以前处理过类似问题，你能找回当时确认的方案，并说明这次需要先核对哪些证据吗？
输出：
{
  "memories": [],
  "experiences": []
}

输入：
[user] 纸舟客服新增了邮件接入。今天网关超时后的重投，又产生了两张工单。
[tool] 查询结果显示同一 tenant_id、同一 event_id 有两张工单。
输出：
{
  "memories": [
    {"content": "用户报告纸舟客服已新增邮件接入", "type": "FACT", "priority": "long_term", "importance": 0.7, "tags": ["纸舟客服", "邮件接入"], "subject": "纸舟客服", "predicate": "已新增", "evidence": "纸舟客服新增了邮件接入"}
  ],
  "experiences": [
    {"content": "排查网关重投重复工单时，应核对同一租户的事件编号是否对应多张工单", "type": "EXPERIENCE", "priority": "long_term", "importance": 0.8, "tags": ["工单", "幂等"], "subject": "重复工单排查", "predicate": "应核对", "evidence": "查询结果显示同一 tenant_id、同一 event_id 有两张工单"}
  ]
}
"""

