EPISODE_EXTRACTION_PROMPT = """
## 任务：情节记忆抽取

从对话历史中抽取一个 **Episode**（情节记忆单元）。

### 输出格式（严格 JSON）
{
  "summary": "100-200字：用户做了什么 + 怎么做的 + 结果如何",
  "goal": "用户的真实意图（不是字面请求）",
  "outcome": "completed | partial | failed | ongoing",
  "entities": ["文件路径1", "项目名", "关键概念1"],
  "tools_used": ["tool_name1", "tool_name2"]
}

### 撰写规范

**summary**：
- 第一句：用户要完成什么任务
- 中间：关键步骤和决策（为什么选这个方法？尝试了什么失败？为什么换路线？）
- 最后：结果如何
- 以用户的事件为主语，直接描述发生了什么；不用“AI 帮助用户”或“用户通过某助手完成了”的套话。

**goal**：
- 回答"用户真正想要什么"，不是"用户说了什么"
- 示例：用户说"帮我部署" → goal: "将应用发布到生产环境并验证可用"

**outcome**：
- completed：目标完全达成
- partial：部分达成（有产出但不完整）
- failed：明确失败（错误、无法完成）
- ongoing：任务进行中，下次对话继续

**entities**：
- 文件路径（如 /tmp/output.png）
- 项目名、仓库名
- 关键概念（API 名称、协议名、库名）

**tools_used**：
- 实际调用的工具名（如 read_file, bash, web_search）
- 推断自操作内容，不是猜测

### 严格过滤
- 不要记录系统内部错误堆栈
- 不要记录 AI 的思考过程
- 工具名用实际调用的，不是 LLM 推断的
"""

